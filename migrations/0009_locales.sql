-- Localisation (docs/specs/content-model/localisation.md).
--
-- One `alter table`, and that is the whole migration. Documents carry their own
-- translations in `Blok.i18n`, and publish still writes one snapshot per story
-- into the same `published_doc` column — which is the strongest evidence that
-- field-level locales in one document (architecture decision 1) fit the existing
-- model rather than fighting it. The rejected alternative, a story row per
-- locale linked by `translation_of`, would have needed a table rebuild, a new
-- index, and a fork of every path derivation in the codebase.
--
-- `stories` is NOT rebuilt here. 0006_document_types.sql already did that to
-- make `path` nullable, and every migration since has been a plain `alter table`
-- on top of it: a second rebuild is a second chance to silently drop a column.

-- Per-locale title cache for the content tree, so a translator's tree is not in
-- English. JSON: { "fr": "À propos", "de": "Über uns" }.
--
-- Best-effort by definition, and deliberately so. `title` remains the
-- source-locale cache and the *document* remains the source of truth for both:
-- a stale cache costs a wrong label in a tree, not wrong content on a page.
-- Written by publish, which is the one path that holds the whole document and
-- therefore every locale's title at once.
alter table stories add column title_i18n text;
